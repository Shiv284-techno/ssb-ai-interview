type Json = Record<string, unknown>;

const asRecord = (value: unknown, what: string): Json =>
  typeof value === "object" && value !== null && !Array.isArray(value)
    ? (value as Json)
    : invalid(`${what} is not an object`);

const asArray = (value: unknown, what: string): unknown[] =>
  Array.isArray(value) ? value : invalid(`${what} is not an array`);

const asString = (value: unknown, what: string): string =>
  typeof value === "string" ? value : invalid(`${what} is not a string`);

const asNumber = (value: unknown, what: string): number =>
  typeof value === "number" && Number.isFinite(value)
    ? value
    : invalid(`${what} is not a finite number`);

function parseAnswerKey(value: unknown, what: string): OirAnswerKey {
  const record = asRecord(value, what);
  const kind = asString(record.kind, `${what}.kind`);
  if (!OIR_ANSWER_KEY_KINDS.includes(kind as OirAnswerKey["kind"])) {
    invalid(`${what}.kind is ${JSON.stringify(kind)}, which is not a known answer form`);
  }
  switch (kind) {
    case "single-option": {
      const optionId = asString(record.optionId, `${what}.optionId`);
      const label = record.label === undefined ? undefined : asString(record.label, `${what}.label`);
      return label === undefined ? { kind, optionId } : { kind, optionId, label };
    }
    case "multiple-options": {
      const ids = asArray(record.optionIds, `${what}.optionIds`).map((id, i) =>
        asString(id, `${what}.optionIds[${i}]`),
      );
      if (ids.length < 2) invalid(`${what} selects fewer than two options`);
      return { kind, optionIds: ids };
    }
    case "ordered-sequence":
    case "multi-token": {
      const values = asArray(record.values, `${what}.values`).map((v, i) =>
        asString(v, `${what}.values[${i}]`),
      );
      if (values.length === 0) invalid(`${what} has no values`);
      return { kind, values };
    }
    case "short-text": {
      const value_ = asString(record.value, `${what}.value`);
      if (value_.length === 0) invalid(`${what} is empty`);
      return { kind, value: value_ };
    }
    case "boolean": {
      if (typeof record.value !== "boolean") invalid(`${what}.value is not a boolean`);
      return { kind, value: record.value };
    }
    default:
      return invalid(`${what}.kind ${JSON.stringify(kind)} is unhandled`);
  }
}

/** Bounds a written answer's shape, so a corrupt file cannot ask for 900 boxes. */
const MAX_RESPONSE_VALUES = 8;
const MAX_RESPONSE_TEXT_LENGTH = 64;

function parseResponseFormat(value: unknown, what: string): OirResponseFormat | null {
  if (value === null || value === undefined) return null;
  const record = asRecord(value, what);
  const kind = asString(record.kind, `${what}.kind`);

  if (kind === "single-option" || kind === "boolean") return { kind };
  if (kind === "multiple-options") {
    const count = asNumber(record.count, `${what}.count`);
    if (!Number.isInteger(count) || count < 2 || count > MAX_RESPONSE_VALUES) {
      invalid(`${what}.count is not a usable number of selections`);
    }
    return { kind, count };
  }
  if (kind === "short-text") {
    const maxLength = asNumber(record.maxLength, `${what}.maxLength`);
    if (!Number.isInteger(maxLength) || maxLength < 1 || maxLength > MAX_RESPONSE_TEXT_LENGTH) {
      invalid(`${what}.maxLength is not a usable length`);
    }
    return { kind, maxLength };
  }
  if (kind === "multi-token" || kind === "ordered-sequence") {
    const count = asNumber(record.count, `${what}.count`);
    if (!Number.isInteger(count) || count < 1 || count > MAX_RESPONSE_VALUES) {
      invalid(`${what}.count is not a usable number of values`);
    }
    return { kind, count };
  }
  return invalid(`${what}.kind is ${JSON.stringify(kind)}, which is not a written answer shape`);
}

function parseStatus(value: unknown, what: string): ContentStatus {
  const status = asString(value, what);
  if (status !== "draft" && status !== "active" && status !== "retired") {
    invalid(`${what} is ${JSON.stringify(status)}, which is not a lifecycle state`);
  }
  return status;
}

type OriginalProvenance = Extract<ContentProvenance, { kind: "original" }>;

function parseProvenance(value: unknown, what: string): OriginalProvenance {
  const record = asRecord(value, what);
  const kind = asString(record.kind, `${what}.kind`);
  if (kind !== "original") {
    // The only provenance this bank is built for. Anything else is a change
    // someone must make deliberately, not something to be waved through.
    invalid(`${what}.kind is ${JSON.stringify(kind)}; this bank only carries original content`);
  }
  return {
    kind: "original",
    author: asString(record.author, `${what}.author`),
    createdAt: asString(record.createdAt, `${what}.createdAt`),
  };
}

function parseOptions(value: unknown, what: string): ChoiceOption[] {
  const options = asArray(value, what).map((option, i) => {
    const record = asRecord(option, `${what}[${i}]`);
    return {
      id: asString(record.id, `${what}[${i}].id`),
      text: asString(record.text, `${what}[${i}].text`),
    };
  });
  const ids = new Set(options.map((option) => option.id));
  if (ids.size !== options.length) invalid(`${what} has duplicate option ids`);
  return options;
}

function parseCurations(value: unknown, what: string): OirCuration[] {
  return asArray(value, what).map((entry, i) => {
    const record = asRecord(entry, `${what}[${i}]`);
    const field = asString(record.field, `${what}[${i}].field`);
    if (field !== "answerKey" && field !== "pictorialOptions") {
      invalid(`${what}[${i}].field ${JSON.stringify(field)} is not curatable`);
    }
    const evidence = asString(record.evidence, `${what}[${i}].evidence`);
    if (evidence.trim().length < MIN_CURATION_EVIDENCE) {
      invalid(`${what}[${i}] cites no substantive evidence`);
    }
    return { field, evidence };
  });
}

