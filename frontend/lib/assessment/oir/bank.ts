export interface OirSet {
  readonly setNumber: number;
  readonly questions: readonly OirQuestionItem[];
  readonly media: ReadonlyMap<MediaAssetId, MediaAsset>;
  readonly omissions: readonly OirOmission[];
  /** How many questions the source book contains, omissions included. */
  readonly sourceQuestionCount: number;
}

const cache = new Map<number, OirSet>();

function loadSet(setNumber: number): OirSet {
  const raw = asRecord(JSON.parse(readFileSync(resolveSetFile(setNumber), "utf8")), "file");
  if (asNumber(raw.setNumber, "setNumber") !== setNumber) {
    invalid(`file for set ${setNumber} declares set ${String(raw.setNumber)}`);
  }
  const setProvenance = parseProvenance(raw.provenance, "provenance");
  const slug = oirSetSlug(setNumber);
  // Read before the questions are walked: it fixes this set's id block, and an
  // id has to be checked against that block as it is parsed.
  const sourceQuestionCount = asNumber(raw.sourceQuestionCount, "sourceQuestionCount");
  const idBlock = idBlockFor(setNumber, sourceQuestionCount);
  const seenIds = new Set<string>();

  const media = new Map<MediaAssetId, MediaAsset>();
  const questions: OirQuestionItem[] = [];
  const seenPositions = new Set<number>();

  for (const [index, entry] of asArray(raw.questions, "questions").entries()) {
    const record = asRecord(entry, `questions[${index}]`);
    const where = `questions[${index}]`;
    const position = asNumber(record.position, `${where}.position`);
    if (seenPositions.has(position)) invalid(`${where} repeats position ${position}`);
    seenPositions.add(position);

    if (!Number.isInteger(position) || position < 1 || position > sourceQuestionCount) {
      invalid(`${where}.position ${position} is not a position in a ${sourceQuestionCount}-question set`);
    }

    const id = contentItemId(asString(record.id, `${where}.id`));
    // Checked against the set's allocated block, NOT against the position.
    //
    // Set 01 allocates its ids by source position and Set 02 allocates them
    // sequentially over accepted records, so `id === position` holds for the
    // first set and for no other. It was the rule here while Set 01 was the
    // only set, which made Set 02 unloadable: `oir.0051` at position 1 is
    // correct under the scheme the ingest tool froze, and was rejected here as
    // a mismatch. The block is the invariant both allocations actually share.
    const idNumber = oirIdNumber(id);
    if (idNumber === null) {
      return invalid(`${where}.id ${JSON.stringify(id)} is not an "oir.NNNN" id`);
    }
    if (idNumber < idBlock.first || idNumber > idBlock.last) {
      invalid(
        `${where}.id ${JSON.stringify(id)} falls outside set ${setNumber}'s allocated id block ` +
          `oir.${String(idBlock.first).padStart(4, "0")}..oir.${String(idBlock.last).padStart(4, "0")}`,
      );
    }
    if (seenIds.has(id)) invalid(`${where}.id ${JSON.stringify(id)} is used twice`);
    seenIds.add(id);
    if (asString(record.type, `${where}.type`) !== "oir-question") {
      invalid(`${where}.type is not "oir-question"`);
    }

    const stem = asString(record.stem, `${where}.stem`);
    const options = parseOptions(record.options, `${where}.options`);
    const optionSource = asString(record.optionSource, `${where}.optionSource`) as OirOptionSource;
    if (optionSource !== "text" && optionSource !== "figure" && optionSource !== "none") {
      invalid(`${where}.optionSource ${JSON.stringify(optionSource)} is not a known source`);
    }
    const pictorialOptionIds = asArray(record.pictorialOptionIds, `${where}.pictorialOptionIds`).map(
      (id, i) => asString(id, `${where}.pictorialOptionIds[${i}]`),
    );
    if (new Set(pictorialOptionIds).size !== pictorialOptionIds.length) {
      invalid(`${where}.pictorialOptionIds repeats a label`);
    }
    if (pictorialOptionIds.some((id) => !/^[0-9]{1,2}$/.test(id))) {
      invalid(`${where}.pictorialOptionIds holds something that is not a numbered choice`);
    }
    const responseFormat = parseResponseFormat(record.responseFormat, `${where}.responseFormat`);
    if (responseFormat === null) invalid(`${where}.responseFormat is missing`);
    // Every question declares how it is answered, and that declaration has to
    // agree with where its choices come from: a question answered by choosing
    // must offer choices, and one answered by writing must not.
    const choosesOption =
      responseFormat.kind === "single-option" || responseFormat.kind === "multiple-options";
    if (choosesOption === (optionSource === "none")) {
      invalid(
        `${where}.optionSource says "${optionSource}" but its response format is ` +
          `"${responseFormat.kind}", which does not match how the question is answered.`,
      );
    }
    if ((optionSource === "figure") !== pictorialOptionIds.length > 0) {
      invalid(`${where}.optionSource says "${optionSource}" but ${pictorialOptionIds.length} pictorial choices are recorded`);
    }
    if ((optionSource === "text") !== options.length > 0) {
      invalid(`${where}.optionSource says "${optionSource}" but ${options.length} options are printed`);
    }

    const figures: OirFigureRef[] = asArray(record.figures, `${where}.figures`).map(
      (reference, figureIndex) => {
        const path = asString(reference, `${where}.figures[${figureIndex}]`);
        if (!isMediaReference(path)) {
          invalid(`${where}.figures[${figureIndex}] ${JSON.stringify(path)} is not a safe media reference`);
        }
        if (!path.startsWith(`oir/${slug}/figures/`)) {
          invalid(`${where}.figures[${figureIndex}] points outside this set's figure directory`);
        }
        // Derived from the GLOBAL question id, not from `position`. Position is
        // per-set, so position-derived figure ids collided across sets — Set 01
        // question 1 and Set 02 question 1 both claimed `oir-figure.00011` —
        // and a combined bank would have served one set's diagram under the
        // other set's id. Set 01's figure ids are unchanged by this, because
        // its id number and its position are the same number.
        const assetId = mediaAssetId(
          `oir-figure.${String(idNumber).padStart(4, "0")}${String(figureIndex + 1)}`,
        );
        media.set(assetId, {
          id: assetId,
          kind: "image",
          reference: path,
          mimeType: "image/png",
          // Deliberately a placeholder. Describing a reasoning diagram without
          // having seen it would put a candidate who relies on alt text in
          // front of a different question from everyone else.
          altText: `${ALT_TEXT_PLACEHOLDER_PREFIX} diagram ${figureIndex + 1} for OIR set ${setNumber} question ${position}.`,
          width: null,
          height: null,
          isIntentionallyIndistinct: false,
          status: "active",
          provenance: setProvenance,
          addedAt: setProvenance.createdAt,
        });
        return { mediaId: assetId, order: figureIndex + 1, needsAltText: true };
      },
    );

    if (stem.length === 0 && figures.length === 0) {
      invalid(`${where} has neither a stem nor a figure`);
    }

    const answerKey = parseAnswerKey(record.answerKey, `${where}.answerKey`);
    const sourcePagesRecord = asRecord(record.sourcePages, `${where}.sourcePages`);
    const explanation = record.explanation === null ? null : asString(record.explanation, `${where}.explanation`);

    const question: OirQuestionItem = {
      id,
      type: "oir-question",
      usedBy: ["oir"],
      version: asNumber(record.version, `${where}.version`),
      // Read, not assumed. Hard-coding "active" here would have made the
      // servability check below unfalsifiable.
      status: parseStatus(record.status, `${where}.status`),
      provenance: parseProvenance(record.provenance, `${where}.provenance`),
      tags: asArray(record.tags, `${where}.tags`).map((tag, i) => asString(tag, `${where}.tags[${i}]`)),
      difficulty: null,
      authoredAt: asString(record.authoredAt, `${where}.authoredAt`),
      editorialNote: record.editorialNote === null ? null : asString(record.editorialNote, `${where}.editorialNote`),
      stem,
      options,
      optionSource,
      pictorialOptionIds,
      responseFormat,
      figures,
      modality: modalityOf({ figures }),
      answerKey,
      explanation,
      setNumber,
      position,
      sourcePages: {
        question: asNumber(sourcePagesRecord.question, `${where}.sourcePages.question`),
        answer: asNumber(sourcePagesRecord.answer, `${where}.sourcePages.answer`),
      },
      curations: parseCurations(record.curations, `${where}.curations`),
    };

    // The two invariants that make a question servable at all: it may be shown,
    // and its answer can be resolved against what it shows.
    if (!isServable(question)) invalid(`${id} is not servable`);
    if (!isAnswerKeyResolvable(question)) {
      invalid(`${id} has an answer key that cannot be resolved against its options or figures`);
    }
    questions.push(question);
  }

  const omissions: OirOmission[] = asArray(raw.omitted, "omitted").map((entry, i) => {
    const record = asRecord(entry, `omitted[${i}]`);
    const pages = asRecord(record.sourcePages, `omitted[${i}].sourcePages`);
    const reasons = asArray(record.reasons, `omitted[${i}].reasons`).map((reason, j) =>
      asString(reason, `omitted[${i}].reasons[${j}]`),
    );
    if (reasons.length === 0) invalid(`omitted[${i}] records no reason`);
    return {
      position: asNumber(record.position, `omitted[${i}].position`),
      reasons,
      sourcePages: {
        question: asNumber(pages.question, `omitted[${i}].sourcePages.question`),
        answer: asNumber(pages.answer, `omitted[${i}].sourcePages.answer`),
      },
    };
  });

  if (questions.length + omissions.length !== sourceQuestionCount) {
    invalid(
      `${questions.length} questions plus ${omissions.length} omissions do not account for ` +
        `the ${sourceQuestionCount} questions in the source`,
    );
  }
  for (const omission of omissions) {
    if (seenPositions.has(omission.position)) {
      invalid(`position ${omission.position} is both served and omitted`);
    }
  }

  return { setNumber, questions, media, omissions, sourceQuestionCount };
}

/** Loads a set, validating it, and keeps it for the life of the process. */
export function getOirSet(setNumber: number): OirSet {
  const cached = cache.get(setNumber);
  if (cached) return cached;
  const set = loadSet(setNumber);
  cache.set(setNumber, set);
  return set;
}

export function getOirQuestion(setNumber: number, position: number): OirQuestionItem | null {
  return getOirSet(setNumber).questions.find((q) => q.position === position) ?? null;
}

export function getOirMedia(setNumber: number, id: MediaAssetId): MediaAsset | null {
  return getOirSet(setNumber).media.get(id) ?? null;
}

/** Why the source's other questions are not here. */
export function omissionsForSet(setNumber: number): readonly OirOmission[] {
  return getOirSet(setNumber).omissions;
}

