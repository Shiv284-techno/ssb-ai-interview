/**
 * Every ingested set, flattened into one bank.
 *
 * A production paper is drawn from all verified content rather than from one
 * set, so something has to hold "all of it" — and that something is the right
 * place to prove the property the whole scheme rests on: that an id means one
 * question. Set 01 alone could not test that, because a single set trivially
 * cannot collide with itself.
 *
 * Questions keep their sets' order, sets in ascending order. That is a stable
 * order, not a meaningful one: selection shuffles, and nothing downstream may
 * read significance into an index here.
 */
export interface OirBank {
  readonly sets: readonly number[];
  readonly questions: readonly OirQuestionItem[];
  readonly media: ReadonlyMap<MediaAssetId, MediaAsset>;
}

let combined: OirBank | null = null;

export function getOirBank(): OirBank {
  if (combined) return combined;

  const questions: OirQuestionItem[] = [];
  const media = new Map<MediaAssetId, MediaAsset>();
  const questionOwner = new Map<string, number>();
  const mediaOwner = new Map<string, number>();

  for (const setNumber of OIR_SETS) {
    const set = getOirSet(setNumber);
    for (const question of set.questions) {
      // The block rule in `loadSet` should already make this impossible. It is
      // asserted anyway: this is the one place the sets meet, a collision here
      // means a candidate could be served one question and marked against
      // another, and an invariant worth the scheme is worth one Map lookup.
      const previous = questionOwner.get(question.id);
      if (previous !== undefined) {
        invalid(`${question.id} is claimed by both set ${previous} and set ${setNumber}`);
      }
      questionOwner.set(question.id, setNumber);
      questions.push(question);
    }
    for (const [id, asset] of set.media) {
      const previous = mediaOwner.get(id);
      if (previous !== undefined) {
        invalid(`media ${id} is claimed by both set ${previous} and set ${setNumber}`);
      }
      mediaOwner.set(id, setNumber);
      media.set(id, asset);
    }
  }

  combined = { sets: OIR_SETS, questions, media };
  return combined;
}

/**
 * A question by its global id, from whichever set holds it.
 *
 * This is what a served paper needs: an attempt records ids, and by the time an
 * answer or a mark comes back, which set the question came from is neither
 * known nor interesting. `getOirQuestion(set, position)` remains for callers
 * that genuinely mean "this set's question N".
 */
export function getOirQuestionById(id: string): OirQuestionItem | null {
  return getOirBank().questions.find((question) => question.id === id) ?? null;
}

/** A figure by its global media id, from whichever set holds it. */
export function getOirMediaById(id: MediaAssetId): MediaAsset | null {
  return getOirBank().media.get(id) ?? null;
}

/** Test seam: forces the next call to re-read and re-validate from disk. */
export function clearOirBankCache(): void {
  cache.clear();
  combined = null;
}
