import "server-only";

/**
 * The OIR question bank.
 *
 * Server-only, and the guard above is the point: this module holds answer keys
 * and explanations, and importing it from a client component must fail the
 * build rather than quietly ship the marks to the browser. Anything a candidate
 * is allowed to see comes out of `toCandidateFacingItem`, never from here.
 *
 * The bank is read from the ingestion tool's output rather than hand-written.
 * That output is produced by `tools/oir-ingest/extract-set.mjs`, which omits any
 * question it cannot recover whole, so each file is already a verified subset:
 * Set 01 contributes 46 of the source's 50, Set 02 contributes 45 and Set 03
 * contributes 43, for 134 across the combined bank. The sixteen that are
 * missing are recorded, with reasons, in `omissionsForSet` — never in the
 * served questions.
 *
 * Loading revalidates everything anyway. The file is build output, and build
 * output can be regenerated by a future version of a tool with a new bug; a
 * bank that trusted it would serve an ungradable question the first time that
 * happened.
 */
import { existsSync, readFileSync } from "node:fs";
import { join, resolve } from "node:path";

import type { ChoiceOption, OirQuestionItem } from "@/lib/assessment/content";
import type { MediaAsset } from "@/lib/assessment/media";
import { isMediaReference } from "@/lib/assessment/media";
import {
  isAnswerKeyResolvable,
  modalityOf,
  OIR_ANSWER_KEY_KINDS,
  type OirAnswerKey,
  type OirCuration,
  type OirFigureRef,
  type OirOmission,
  type OirOptionSource,
  type OirResponseFormat,
} from "@/lib/assessment/oir/types";
import {
  contentItemId,
  isServable,
  mediaAssetId,
  type ContentProvenance,
  type ContentStatus,
  type MediaAssetId,
} from "@/lib/assessment/types";

/** Alt text is authored by a person, never generated from the picture. */
const ALT_TEXT_PLACEHOLDER_PREFIX = "Figure not yet described:";
const MIN_CURATION_EVIDENCE = 40;

class OirBankError extends Error {}

function invalid(message: string): never {
  // Bank content is authored, never candidate data, so quoting it here is safe.
  throw new OirBankError(`OIR bank: ${message}`);
}

/**
 * Where the ingested content lives.
 *
 * The tool writes to `content/` at the repository root, beside `docs/` and
 * `tools/`, so the same tree serves every app that might later read it. Next
 * runs with the frontend as its working directory, hence the step upward; the
 * plain path is tried too so the loader keeps working if the content is ever
 * vendored into the app.
 */
export function oirContentRoot(): string {
  const candidates = [
    join(process.cwd(), "..", "content", "oir"),
    join(process.cwd(), "content", "oir"),
  ];
  for (const candidate of candidates) {
    if (existsSync(candidate)) return resolve(candidate);
  }
  return invalid(
    `the content root was not found. Run "node tools/oir-ingest/extract-set.mjs --set 1" ` +
      `to produce it. Looked in: ${candidates.join(", ")}`,
  );
}

export const oirSetSlug = (setNumber: number): string =>
  `set-${String(setNumber).padStart(2, "0")}`;

/**
 * The sets that have been ingested and verified, in order.
 *
 * One list, exported, because "which sets exist" was previously written out
 * separately in the attempt service and in two routes, and three copies of a
 * fact is three chances for a set to be ingested and then silently ignored by
 * one of them.
 */
export const OIR_SETS: readonly number[] = [1, 2, 3];

/**
 * The block of the global id sequence a set owns.
 *
 * There is ONE id space across the whole book — `oir.NNNN` — and each set owns
 * a contiguous block of it `sourceQuestionCount` wide, starting where the
 * previous set's block ended. Set 01 owns 1..50 and Set 02 owns 51..100, which
 * is exactly what `SET_ID_START` in `tools/oir-ingest/extract-set.mjs`
 * allocates; this is the same rule stated as an interval rather than as a
 * table, so a third set needs no edit here.
 *
 * Checking the block rather than the individual number is what makes global
 * uniqueness structural. Ids drawn from disjoint blocks cannot collide, so the
 * combined bank does not have to hope that two sets happened not to overlap —
 * and an ingest tool that regressed to per-set numbering is caught on load
 * rather than after a candidate has been served two different questions under
 * one id.
 */
function idBlockFor(
  setNumber: number,
  sourceQuestionCount: number,
): { readonly first: number; readonly last: number } {
  const first = (setNumber - 1) * sourceQuestionCount + 1;
  return { first, last: first + sourceQuestionCount - 1 };
}

/** The numeric part of an `oir.NNNN` id, or null if it is not one. */
function oirIdNumber(id: string): number | null {
  const match = /^oir\.([0-9]{4})$/.exec(id);
  return match ? Number(match[1]) : null;
}

function resolveSetFile(setNumber: number): string {
  const file = join(oirContentRoot(), oirSetSlug(setNumber), "questions.json");
  if (!existsSync(file)) {
    invalid(
      `set ${setNumber} was not found. Run ` +
        `"node tools/oir-ingest/extract-set.mjs --set ${setNumber}" to produce it.`,
    );
  }
  return file;
}

